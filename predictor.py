def get_stock_list():
    """Return sorted list of available PSX stocks."""
    stocks = []
    for ticker, info in PSX_STOCKS.items():
        stocks.append({
            "ticker": ticker,
            "name": info["name"],
            "sector": info["sector"],
            "display": f"{info['name']} ({ticker.replace('.KA', '')})"
        })
    return sorted(stocks, key=lambda x: x["name"])


def get_sectors():
    """Return unique sectors."""
    sectors = set(info["sector"] for info in PSX_STOCKS.values())
    return sorted(sectors)


def fetch_stock_data(ticker, period="2y"):
    """
    Load historical stock data from local CSV files.

    Args:
        ticker: Ticker symbol (e.g., 'OGDC.KA')
        period: Data period filter ('6mo', '1y', '2y', '5y', 'max')

    Returns:
        DataFrame with stock data or None if file not found
    """
    try:
        filename = ticker.replace(".", "_") + ".csv"
        filepath = os.path.join(DATA_DIR, filename)

        if not os.path.exists(filepath):
            return None

        df = pd.read_csv(filepath)
        df['Date'] = pd.to_datetime(df['Date'])

        # Filter based on period
        if period != 'max':
            period_map = {
                '6mo': 180,
                '1y': 365,
                '2y': 730,
                '5y': 1825,
            }
            days = period_map.get(period, 730)
            cutoff = df['Date'].max() - timedelta(days=days)
            df = df[df['Date'] >= cutoff].reset_index(drop=True)

        return df
    except Exception as e:
        print(f"Error loading data for {ticker}: {e}")
        return None


def calculate_technical_indicators(df):
    """
    Calculate technical indicators for stock analysis.

    Indicators computed:
    - SMA (Simple Moving Average) 20, 50, 200 days
    - EMA (Exponential Moving Average) 12, 26 days
    - RSI (Relative Strength Index) 14 days
    - MACD (Moving Average Convergence Divergence)
    - Bollinger Bands (20 day, 2 std)
    - Daily Returns & Volatility
    """
    df = df.copy()

    # Simple Moving Averages
    df['SMA_20'] = df['Close'].rolling(window=20).mean()
    df['SMA_50'] = df['Close'].rolling(window=50).mean()
    df['SMA_200'] = df['Close'].rolling(window=200).mean()

    # Exponential Moving Averages
    df['EMA_12'] = df['Close'].ewm(span=12, adjust=False).mean()
    df['EMA_26'] = df['Close'].ewm(span=26, adjust=False).mean()

    # RSI (Relative Strength Index)
    delta = df['Close'].diff()
    gain = (delta.where(delta > 0, 0)).rolling(window=14).mean()
    loss = (-delta.where(delta < 0, 0)).rolling(window=14).mean()
    rs = gain / loss
    df['RSI'] = 100 - (100 / (1 + rs))

    # MACD
    df['MACD'] = df['EMA_12'] - df['EMA_26']
    df['MACD_Signal'] = df['MACD'].ewm(span=9, adjust=False).mean()
    df['MACD_Histogram'] = df['MACD'] - df['MACD_Signal']

    # Bollinger Bands
    df['BB_Middle'] = df['Close'].rolling(window=20).mean()
    bb_std = df['Close'].rolling(window=20).std()
    df['BB_Upper'] = df['BB_Middle'] + (bb_std * 2)
    df['BB_Lower'] = df['BB_Middle'] - (bb_std * 2)

    # Daily Returns
    df['Daily_Return'] = df['Close'].pct_change() * 100

    # Volatility (20-day rolling standard deviation of returns)
    df['Volatility'] = df['Daily_Return'].rolling(window=20).std()

    return df


def prepare_features(df, lookback=20):
    """
    Prepare features for the Linear Regression model.

    Features include:
    - Lagged closing prices (past N days)
    - Moving averages (5, 10, 20 day)
    - Price momentum (5, 10 day)
    - Volume moving average
    - Day number (trend feature)
    """
    df = df.copy()

    # Lagged features
    for i in range(1, lookback + 1):
        df[f'Close_Lag_{i}'] = df['Close'].shift(i)

    # Moving average features
    df['MA_5'] = df['Close'].rolling(5).mean()
    df['MA_10'] = df['Close'].rolling(10).mean()
    df['MA_20'] = df['Close'].rolling(20).mean()

    # Price momentum
    df['Momentum_5'] = df['Close'] - df['Close'].shift(5)
    df['Momentum_10'] = df['Close'] - df['Close'].shift(10)

    # Volume moving average
    df['Volume_MA_5'] = df['Volume'].rolling(5).mean()

    # Day number feature (for trend)
    df['Day_Number'] = np.arange(len(df))

    # Drop NaN rows
    df = df.dropna()

    return df


def predict_stock_prices(ticker, prediction_days=30, period="2y"):
    """
    Predict future stock prices using Linear Regression.

    This function:
    1. Loads historical data from local CSV files
    2. Calculates technical indicators
    3. Prepares feature matrix with lagged prices, MAs, momentum
    4. Trains a Linear Regression model
    5. Iteratively predicts future prices

    Args:
        ticker: Stock ticker symbol (e.g., 'OGDC.KA')
        prediction_days: Number of future trading days to predict (1-90)
        period: Historical data period ('6mo', '1y', '2y', '5y')

    Returns:
        Dictionary containing prediction results, metrics, and analysis data
    """
    # ── Load data ──
    df = fetch_stock_data(ticker, period)
    if df is None or len(df) < 60:
        return {"error": "Insufficient data available for this stock. Try a different period."}

    # ── Calculate technical indicators for analysis ──
    df_analysis = calculate_technical_indicators(df)

    # ── Prepare features for prediction ──
    lookback = 20
    df_features = prepare_features(df, lookback=lookback)

    if len(df_features) < 30:
        return {"error": "Not enough data after feature preparation."}

    # ── Define feature columns ──
    feature_cols = [f'Close_Lag_{i}' for i in range(1, lookback + 1)]
    feature_cols += ['MA_5', 'MA_10', 'MA_20', 'Momentum_5', 'Momentum_10',
                     'Volume_MA_5', 'Day_Number']

    X = df_features[feature_cols].values
    y = df_features['Close'].values

    # ── Train/Test Split (80/20, no shuffle for time series) ──
    X_train, X_test, y_train, y_test = train_test_split(
        X, y, test_size=0.2, shuffle=False
    )

    # ── Train Linear Regression Model ──
    model = LinearRegression()
    model.fit(X_train, y_train)

    # ── Model Evaluation ──
    y_pred_test = model.predict(X_test)
    mae = mean_absolute_error(y_test, y_pred_test)
    rmse = np.sqrt(mean_squared_error(y_test, y_pred_test))
    r2 = r2_score(y_test, y_pred_test)
    mape = np.mean(np.abs((y_test - y_pred_test) / y_test)) * 100

    # ── Predict Future Prices ──
    last_row = df_features.iloc[-1]
    future_prices = []
    current_features = last_row[feature_cols].values.reshape(1, -1)
    last_known_prices = list(df['Close'].values[-lookback:])

    for day in range(prediction_days):
        pred_price = model.predict(current_features)[0]
        future_prices.append(pred_price)

        # Update features for next prediction
        last_known_prices.append(pred_price)
        new_lags = last_known_prices[-(lookback):][::-1]

        # Recalculate rolling features
        ma_5 = np.mean(last_known_prices[-5:])
        ma_10 = np.mean(last_known_prices[-10:])
        ma_20 = np.mean(last_known_prices[-20:])
        momentum_5 = pred_price - last_known_prices[-6] if len(last_known_prices) > 5 else 0
        momentum_10 = pred_price - last_known_prices[-11] if len(last_known_prices) > 10 else 0
        vol_ma = current_features[0][-2]
        day_num = current_features[0][-1] + 1

        new_features = list(new_lags) + [ma_5, ma_10, ma_20, momentum_5,
                                          momentum_10, vol_ma, day_num]
        current_features = np.array(new_features).reshape(1, -1)

    # ── Generate future dates (skip weekends) ──
    last_date = df['Date'].iloc[-1]
    future_dates = []
    current_date = last_date
    for _ in range(prediction_days):
        current_date += timedelta(days=1)
        while current_date.weekday() >= 5:
            current_date += timedelta(days=1)
        future_dates.append(current_date)

    # ── Determine trading signal ──
    current_price = float(df['Close'].iloc[-1])
    predicted_end = float(future_prices[-1])
    price_change_pct = ((predicted_end - current_price) / current_price) * 100

    if price_change_pct > 5:
        signal = "🟢 Strong Buy"
    elif price_change_pct > 2:
        signal = "🟢 Buy"
    elif price_change_pct > -2:
        signal = "🟡 Hold"
    elif price_change_pct > -5:
        signal = "🔴 Sell"
    else:
        signal = "🔴 Strong Sell"

    # ── Get latest indicator values ──
    latest = df_analysis.iloc[-1]
    stock_info = PSX_STOCKS.get(ticker, {"name": ticker, "sector": "Unknown"})

    # ── Build result dictionary ──
    result = {
        "ticker": ticker,
        "name": stock_info["name"],
        "sector": stock_info["sector"],
        "current_price": round(current_price, 2),
        "predicted_price": round(predicted_end, 2),
        "price_change_pct": round(price_change_pct, 2),
        "signal": signal,

        # Historical data for charts
        "df_historical": df,
        "df_analysis": df_analysis,

        # Predicted data
        "predicted_dates": future_dates,
        "predicted_prices": [round(float(p), 2) for p in future_prices],

        # Technical indicators (latest values)
        "sma_20": round(float(latest['SMA_20']), 2) if pd.notna(latest.get('SMA_20')) else None,
        "sma_50": round(float(latest['SMA_50']), 2) if pd.notna(latest.get('SMA_50')) else None,
        "sma_200": round(float(latest['SMA_200']), 2) if pd.notna(latest.get('SMA_200')) else None,
        "rsi": round(float(latest['RSI']), 2) if pd.notna(latest.get('RSI')) else None,
        "macd": round(float(latest['MACD']), 4) if pd.notna(latest.get('MACD')) else None,
        "macd_signal_line": round(float(latest['MACD_Signal']), 4) if pd.notna(latest.get('MACD_Signal')) else None,

        # Model metrics
        "mae": round(mae, 2),
        "rmse": round(rmse, 2),
        "r2_score": round(r2, 4),
        "mape": round(mape, 2),

        # Summary stats
        "day_change": round(float(df['Close'].iloc[-1] - df['Close'].iloc[-2]), 2) if len(df) > 1 else 0,
        "day_change_pct": round(float((df['Close'].iloc[-1] - df['Close'].iloc[-2]) / df['Close'].iloc[-2] * 100), 2) if len(df) > 1 else 0,
        "high_52w": round(float(df['High'].tail(252).max()), 2),
        "low_52w": round(float(df['Low'].tail(252).min()), 2),
        "avg_volume": int(df['Volume'].tail(30).mean()),

        # Test predictions for accuracy chart
        "y_test": y_test.tolist(),
        "y_pred_test": y_pred_test.tolist(),
    }

    return result
